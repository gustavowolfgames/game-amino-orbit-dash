// bun run init-game <slug> "<Title>" — make this copy of the template your game.
//
// A fresh copy still carries the template's identity: its Nucleo slug, its asset
// lockfile (files published under the template's slug, so under a new slug they 404
// and the loader hangs), its package name and its title. This sets them in one go:
//
//   wolf-game-kit.json             gameSlug, projectId (must equal it), gameName
//   .env.example (and .env)        VITE_GAME_KIT_PROJECT_ID
//   package.json                   name
//   src/game/config.ts             GAME_TITLE
//   docs/GAME-DESIGN.md            the title in its heading
//   assets/asset-manifest.cdn.json the lockfile, emptied (no files, no releaseId)
//   assets/registry.ts             its codegen, emptied to match
//
// Save keys, the content catalog and the flag cache key read the slug from
// wolf-game-kit.json or the env, so they follow without an edit here.
//
// It only writes files. Registering the game in Nucleo and publishing assets are
// printed as next steps, never run. Running it again with the same arguments changes
// nothing. It refuses a dirty git tree unless --force, so its diff stands alone.
//
// Some lockfile files exist only on the template's CDN, with no copy in public/assets/
// (the template's music). Emptying the lockfile would leave the game silently without
// them, so it refuses until they are staged in assets/src/ for the game's first publish:
// run the wolf-game-kit MCP assets_pull first, while the slug is still the template's.
// --skip-cdn-only goes on without them (the game will publish its own).
//
//   bun run init-game ballblast "Ball Blast"
//   bun run init-game mygame "My Game"        local-only build: no Nucleo slug yet
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** This template's own Nucleo slug (as in check-agent-surface.mjs). A game never takes it. */
const TEMPLATE_SLUG = 'aminoecspure';
/** A bare Nucleo slug: never `<slug>_<uuid>`, which splits publishes from what players load. */
const SLUG_PATTERN = /^[a-z0-9][a-z0-9-]*$/;

/** The empty lockfile and its codegen, exactly as the kits ship them. */
const EMPTY_LOCKFILE = `${JSON.stringify({ version: 1, files: {} }, null, 2)}\n`;
const EMPTY_REGISTRY = `// Auto-generated by wolf-dev CLI (\`assets publish\`). Do not edit manually.
import type { AssetSeed } from '@wolfgames/client';

/** The committed lockfile, baked in as the synchronous boot seed. */
export const assetSeed = {
  version: 1,
  files: {},
} as const satisfies AssetSeed;

/** Lockfile-derived asset names — \`assets.url()\` typos fail typecheck. */
export type AssetName = keyof typeof assetSeed.files;
`;

const args = process.argv.slice(2);
const FLAGS = ['--force', '--skip-cdn-only'];
const force = args.includes('--force');
const skipCdnOnly = args.includes('--skip-cdn-only');
const [slug, title] = args.filter((a) => !FLAGS.includes(a));
const usage =
  'usage: bun run init-game <slug> "<Title>" [--force] [--skip-cdn-only]';

if (!slug || !title?.trim()) {
  console.error(usage);
  process.exit(1);
}
if (!SLUG_PATTERN.test(slug)) {
  console.error(
    `"${slug}" is not a bare Nucleo slug: lowercase letters, digits and hyphens, starting with a letter or digit${slug.includes('_') ? ' (never <slug>_<uuid>: use the bare slug)' : ''}.`,
  );
  process.exit(1);
}
if (slug === TEMPLATE_SLUG) {
  console.error(
    `"${TEMPLATE_SLUG}" is the template's own slug. Use the game's Nucleo slug, or "mygame" for a local-only build.`,
  );
  process.exit(1);
}

// A dirty tree would mix this script's diff with other work. Outside git there is
// nothing to protect.
if (!force) {
  let dirty = '';
  try {
    dirty = execFileSync('git', ['status', '--porcelain'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    // not a git repository
  }
  if (dirty) {
    console.error(
      `Refusing: the git tree has uncommitted changes. Commit or stash them first, or pass --force.\n${dirty}`,
    );
    process.exit(1);
  }
}

// Lockfile files the game would lose: published only under the template's slug, with no
// stand-in in public/assets/ (local dev serves those until the first publish).
const LOCKFILE = 'assets/asset-manifest.cdn.json';
const lockfileFiles = existsSync(path.join(root, LOCKFILE))
  ? Object.keys(
      JSON.parse(readFileSync(path.join(root, LOCKFILE), 'utf8')).files ?? {},
    )
  : [];
const cdnOnly = lockfileFiles.filter(
  (f) => !existsSync(path.join(root, 'public/assets', f)),
);
const staged = cdnOnly.filter((f) =>
  existsSync(path.join(root, 'assets/src', f)),
);
const unstaged = cdnOnly.filter((f) => !staged.includes(f));
const localOnly = slug === 'mygame';

if (unstaged.length && !skipCdnOnly && !localOnly) {
  console.error(
    `Refusing: these files exist only on the template's CDN, and nothing in public/assets/ stands in for them:
${unstaged.map((f) => `  ${f}`).join('\n')}
Emptying the lockfile would leave the game without them (an audio-* bundle plays silent).
Keep them: run the wolf-game-kit MCP assets_pull now, while the slug is still the template's; it
stages them in assets/src/ (gitignored) for the game's first assets_publish. Then rerun this.
Or pass --skip-cdn-only to go on without them, if the game will publish its own.`,
  );
  process.exit(1);
}

const changed = [];
/** Writes `file` when `edit(current)` differs from what is there; records it. */
function update(file, edit, { optional = false } = {}) {
  const p = path.join(root, file);
  if (!existsSync(p)) {
    if (optional) return;
    console.error(`missing ${file}: is this a copy of the template?`);
    process.exit(1);
  }
  const before = readFileSync(p, 'utf8');
  const after = edit(before);
  if (after !== before) {
    writeFileSync(p, after);
    changed.push(file);
  }
}
/** Edits a JSON file in place, keeping its 2-space layout and key order. */
const updateJson = (file, edit) =>
  update(
    file,
    (text) => `${JSON.stringify(edit(JSON.parse(text)), null, 2)}\n`,
  );
/** Sets `KEY=value` in an env file, leaving every other line alone. */
const setEnv = (key, value) => (text) =>
  text.replace(new RegExp(`^${key}=.*$`, 'm'), `${key}=${value}`);

updateJson('wolf-game-kit.json', (cfg) => ({
  ...cfg,
  projectId: slug,
  gameSlug: slug,
  gameName: title,
}));
update('.env.example', setEnv('VITE_GAME_KIT_PROJECT_ID', slug));
update('.env', setEnv('VITE_GAME_KIT_PROJECT_ID', slug), { optional: true });
updateJson('package.json', (pkg) => ({ ...pkg, name: slug }));
update('src/game/config.ts', (text) =>
  text.replace(
    /^export const GAME_TITLE = .*;$/m,
    `export const GAME_TITLE = '${title.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}';`,
  ),
);
update(
  'docs/GAME-DESIGN.md',
  (text) => text.replace(/^# Game Design — .*$/m, `# Game Design — ${title}`),
  { optional: true },
);
update('assets/asset-manifest.cdn.json', () => EMPTY_LOCKFILE);
update('assets/registry.ts', () => EMPTY_REGISTRY);

if (changed.length) {
  console.log(`✓ "${title}" on slug "${slug}" (${changed.length} files):`);
  for (const f of changed) console.log(`  ${f}`);
} else {
  console.log(`✓ already "${title}" on slug "${slug}": nothing to change.`);
}

const list = (files) => files.join(', ');
const next = localOnly
  ? [
      '"mygame" is local-only: do not publish under it. Rerun with the real slug once Nucleo has one.',
      'cp .env.example .env && bun install',
    ]
  : [
      `Register "${slug}" in Nucleo if it is not already (wolf-game-kit MCP game_create / game_setup, or ask whoever owns Nucleo). The slug must match exactly.`,
      'cp .env.example .env && bun install',
      ...(staged.length
        ? [
            `Publish the template files staged in assets/src/ under "${slug}" with the wolf-game-kit MCP assets_publish (${list(staged)}); they do not load until then.`,
          ]
        : []),
      "Until the first assets_publish, local dev serves public/assets/. Publish the game's own art with the wolf-game-kit MCP (.agents/recipes/assets.md), then commit assets/asset-manifest.cdn.json and assets/registry.ts.",
    ];
if (unstaged.length && changed.includes(LOCKFILE))
  console.log(
    `\n⚠ Left behind on the template's CDN, so they do not load in this game: ${list(unstaged)}.${localOnly ? ' A local-only build plays without them.' : " Publish replacements under the game's slug."}`,
  );
console.log('\nNext (not run by this script):');
for (const [i, s] of next.entries()) console.log(`  ${i + 1}. ${s}`);
console.log('  Then carry on with .agents/recipes/new-game.md step 3.');
